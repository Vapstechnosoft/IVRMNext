// Helper function to get icon by name
export const getIconByName = (iconName: string): LucideIcon | null => {
    const iconOption = lucideIcons.find((icon) => icon.name === iconName);
    return iconOption ? iconOption.icon : null;
};

// Helper function to get icons by category
export const getIconsByCategory = (category: string): IconOption[] => {
    return lucideIcons.filter((icon) => icon.category === category);
};

// Helper function to get all categories
export const getAllCategories = (): string[] => {
    return Object.values(iconCategories);
};
